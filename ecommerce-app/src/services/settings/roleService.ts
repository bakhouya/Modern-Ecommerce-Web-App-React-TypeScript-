

/* ---------------------------------------------------------------------------------*/
/* ---------------------------------------------------------------------------------*/
import api from '../axiosInstance';
import type { GroupTypes, PermissionGroupTypes, RoleFilterTypes, RoleFormData, RoleResponseTypes, RoleTypes } from '../../types/RolesTypes';
/* ---------------------------------------------------------------------------------*/

/* ---------------------------------------------------------------------------------*/
/* ---------------------------------------------------------------------------------*/
const BASE_URL = '/panel/groups/';
/* ---------------------------------------------------------------------------------*/

/* ---------------------------------------------------------------------------------*/
/* ---------------------------------------------------------------------------------*/
export const RoleService = {

    /* -----------------------------------------------------------------------------*/
    /* -----------------------------------------------------------------------------*/
    async getAll(params?: RoleFilterTypes): Promise<RoleResponseTypes> {
      const response = await api.get<RoleResponseTypes>(BASE_URL, { params });
      return response.data; 
    },
    /* -----------------------------------------------------------------------------*/

    /* -----------------------------------------------------------------------------*/
    /* -----------------------------------------------------------------------------*/
    async create(data: RoleFormData): Promise<RoleTypes> {
      const response = await api.post<RoleTypes>(BASE_URL, data);
      return response.data;
    },
    /* -----------------------------------------------------------------------------*/

    /* -----------------------------------------------------------------------------*/
    /* -----------------------------------------------------------------------------*/
    async update(id: string | number, data: RoleFormData): Promise<RoleTypes> {
      const response = await api.put<RoleTypes>(`${BASE_URL}${id}/`, data);
      return response.data;
    },
    /* -----------------------------------------------------------------------------*/

    /* -----------------------------------------------------------------------------*/
    /* -----------------------------------------------------------------------------*/
    async delete(id: string | number): Promise<void> {
      await api.delete(`${BASE_URL}${id}/`);
    },
    /* -----------------------------------------------------------------------------*/
    
    /* -----------------------------------------------------------------------------*/
    /* -----------------------------------------------------------------------------*/
    async bulkDelete(ids: (string | number)[]): Promise<void> {
      await api.delete(`${BASE_URL}bulk-delete/`, { data: { ids } });
    },
    /* -----------------------------------------------------------------------------*/

};
/* ---------------------------------------------------------------------------------*/


/* ---------------------------------------------------------------------------------*/
/* ---------------------------------------------------------------------------------*/
export const PermissionsService = async (): Promise<PermissionGroupTypes[]> => {
    const response = await api.get('/panel/permissions/');
    return response.data;
};
/* ---------------------------------------------------------------------------------*/

/* ---------------------------------------------------------------------------------*/
/* ---------------------------------------------------------------------------------*/
export const GroupsService = async (): Promise<GroupTypes[]> => {
    const response = await api.get('/panel/roles/');
    return response.data ;
};
/* ---------------------------------------------------------------------------------*/


