import api from '../axiosInstance';
import type { CityTypes, CityFormData, ApiPaginatedResponse, CityParamsFilterTypes } from '../../types/cityTypes';
import type { CityType } from '../../types/dashboard/city';
/* ---------------------------------------------------------------------------------*/

/* ---------------------------------------------------------------------------------*/
/* ---------------------------------------------------------------------------------*/
const BASE_URL = '/panel/cities/';
/* ---------------------------------------------------------------------------------*/

/* ---------------------------------------------------------------------------------*/
/* ---------------------------------------------------------------------------------*/
export const cityService = {

    /* -----------------------------------------------------------------------------*/
    /* -----------------------------------------------------------------------------*/
    async getAll(params: CityParamsFilterTypes): Promise<ApiPaginatedResponse<CityTypes>> {
      const response = await api.get<ApiPaginatedResponse<CityTypes>>(BASE_URL, { params });
      return response.data; 
    },
    /* -----------------------------------------------------------------------------*/

    /* -----------------------------------------------------------------------------*/
    /* -----------------------------------------------------------------------------*/
    async create(data: CityFormData): Promise<CityTypes> {
      const response = await api.post<CityTypes>(BASE_URL, data);
      return response.data;
    },
    /* -----------------------------------------------------------------------------*/

    /* -----------------------------------------------------------------------------*/
    /* -----------------------------------------------------------------------------*/
    async update(id: string | number, data: CityFormData): Promise<CityTypes> {
      const response = await api.put<CityTypes>(`${BASE_URL}${id}/`, data);
      return response.data;
    },
    /* -----------------------------------------------------------------------------*/

    /* -----------------------------------------------------------------------------*/
    /* -----------------------------------------------------------------------------*/
    async delete(id: string | number): Promise<void> {
      await api.delete(`${BASE_URL}${id}/`);
    },
    /* -----------------------------------------------------------------------------*/
    
    /* -----------------------------------------------------------------------------*/
    /* -----------------------------------------------------------------------------*/
    async bulkDelete(ids: (string | number)[]): Promise<void> {
      await api.delete(`${BASE_URL}bulk-delete/`, { data: { ids } });
    },
    /* -----------------------------------------------------------------------------*/

};
/* ---------------------------------------------------------------------------------*/


/* ---------------------------------------------------------------------------------*/
/* ---------------------------------------------------------------------------------*/
export const ActiveCitiesService = async (): Promise<CityType[]> => {
  const response = await api.get('/public/cities/active/');
  return response.data;
};
