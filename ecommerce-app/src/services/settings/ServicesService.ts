/* ---------------------------------------------------------------------------------*/
import api from '../axiosInstance';
import type { ServiceApiPaginatedResponse, ServiceFormData, ServiceFilterTypes, ServiceTypes} from '../../types/serviceTypes';
import { StoreApi } from '../storeApi';
/* ---------------------------------------------------------------------------------*/


/* ---------------------------------------------------------------------------------*/
/* ---------------------------------------------------------------------------------*/
const BASE_URL = '/panel/services/';
/* ---------------------------------------------------------------------------------*/

/* ---------------------------------------------------------------------------------*/
/* ---------------------------------------------------------------------------------*/
export const ServicesService = {
    /* -----------------------------------------------------------------------------*/
    /* -----------------------------------------------------------------------------*/
    async getAll(params?: ServiceFilterTypes): Promise<ServiceApiPaginatedResponse<ServiceTypes>> {
      const response = await api.get<ServiceApiPaginatedResponse<ServiceTypes>>(BASE_URL, { params });
      return response.data; 
    },
    /* -----------------------------------------------------------------------------*/
    
    /* -----------------------------------------------------------------------------*/
    /* -----------------------------------------------------------------------------*/
    async create(data: ServiceFormData): Promise<ServiceTypes> {
        const response = await api.post<ServiceTypes>(BASE_URL, data, {
            headers: { 'Content-Type': 'multipart/form-data' }
        });
        return response.data;
    },
    /* -----------------------------------------------------------------------------*/

    /* -----------------------------------------------------------------------------*/
    /* -----------------------------------------------------------------------------*/
    async update(id: string | number, data: ServiceFormData): Promise<ServiceTypes> {
        const response = await api.put<ServiceTypes>(`${BASE_URL}${id}/`, data, {
            headers: { 'Content-Type': 'multipart/form-data' }
        });
        return response.data;
    },
    /* -----------------------------------------------------------------------------*/

    /* -----------------------------------------------------------------------------*/
    /* -----------------------------------------------------------------------------*/
    async delete(id: string | number): Promise<void> {
      await api.delete(`${BASE_URL}${id}/`);
    },
    /* -----------------------------------------------------------------------------*/

    /* -----------------------------------------------------------------------------*/
    /* -----------------------------------------------------------------------------*/
    async bulkDelete(ids: (string | number)[]): Promise<void> {
      await api.delete(`${BASE_URL}bulk-delete/`, { data: { ids } });
    },
    /* -----------------------------------------------------------------------------*/


};
/* ---------------------------------------------------------------------------------*/


/* ---------------------------------------------------------------------------------*/
/* ---------------------------------------------------------------------------------*/
export const PublicServices = async (): Promise<ServiceTypes[]> => {
  const response = await StoreApi.get('/public/services//');
  return response.data;
};
