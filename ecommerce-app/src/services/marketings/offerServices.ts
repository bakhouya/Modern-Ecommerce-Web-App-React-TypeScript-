import api from '../axiosInstance'; 
import type { OfferFilterTypes, OfferFormData, OfferPaginatedResponse, OfferTypes, OfferWithPrudctsTypes } from '../../types/offersTypes';
import { StoreApi } from '../storeApi';
/* ---------------------------------------------------------------------------------*/


/* ---------------------------------------------------------------------------------*/
/* ---------------------------------------------------------------------------------*/
const BASE_URL = '/panel/offers/' ;
/* ---------------------------------------------------------------------------------*/

/* ---------------------------------------------------------------------------------*/
/* ---------------------------------------------------------------------------------*/
export const OfferService = {
    /* -----------------------------------------------------------------------------*/
    /* -----------------------------------------------------------------------------*/
    async getAll(params?: OfferFilterTypes): Promise<OfferPaginatedResponse> {
      const response = await api.get<OfferPaginatedResponse>(BASE_URL, { params });
      return response.data; 
    },
    /* -----------------------------------------------------------------------------*/
    
    /* -----------------------------------------------------------------------------*/
    /* -----------------------------------------------------------------------------*/
    async create(data: OfferFormData): Promise<OfferTypes> {
        const response = await api.post<OfferTypes>(BASE_URL, data, {
            headers: { 'Content-Type': 'multipart/form-data' }
        });
        return response.data;
    },
    /* -----------------------------------------------------------------------------*/

    /* -----------------------------------------------------------------------------*/
    /* -----------------------------------------------------------------------------*/
    async update(id: string | number, data: OfferFormData): Promise<OfferTypes> {
        const response = await api.put<OfferTypes>(`${BASE_URL}${id}/`, data, {
            headers: { 'Content-Type': 'multipart/form-data' }
        });
        return response.data;
    },
    /* -----------------------------------------------------------------------------*/


    /* -----------------------------------------------------------------------------*/
    /* -----------------------------------------------------------------------------*/
    async edit(id: string | number): Promise<OfferTypes> {
        const response = await api.get<OfferTypes>(`${BASE_URL}${id}/`);
        return response.data;
    },
    /* -----------------------------------------------------------------------------*/


    /* -----------------------------------------------------------------------------*/
    /* -----------------------------------------------------------------------------*/
    async delete(id: string | number): Promise<void> {
      await api.delete(`${BASE_URL}${id}/`);
    },
    /* -----------------------------------------------------------------------------*/

    /* -----------------------------------------------------------------------------*/
    /* -----------------------------------------------------------------------------*/
    async bulkDelete(ids: (string | number)[]): Promise<void> {
      await api.delete(`${BASE_URL}bulk-delete/`, { data: { ids } });
    },
    /* -----------------------------------------------------------------------------*/
};
/* ---------------------------------------------------------------------------------*/



/* ---------------------------------------------------------------------------------*/
/* ---------------------------------------------------------------------------------*/
export const PublicOffers = async (): Promise<OfferTypes[]> => {
    const response = await StoreApi.get('/public/offers/');
    return response.data ;
};
/* ---------------------------------------------------------------------------------*/

/* ---------------------------------------------------------------------------------*/
/* ---------------------------------------------------------------------------------*/
export const GetPoductsOffer = async (id: string ): Promise<OfferWithPrudctsTypes> => {
    const response = await StoreApi.get(`/public/offers/${id}/`);
    return response.data ;
};
