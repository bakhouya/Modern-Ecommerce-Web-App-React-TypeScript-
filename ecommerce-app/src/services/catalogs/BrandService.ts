




/* ---------------------------------------------------------------------------------*/
/* ---------------------------------------------------------------------------------*/
import api from '../axiosInstance'; 
import type { BrandApiPaginatedResponse, BrandFilterTypes, BrandForCreateTypes, BrandFormData, BrandTypes } from '../../types/brandTypes';
import { StoreApi } from '../storeApi';
/* ---------------------------------------------------------------------------------*/


/* ---------------------------------------------------------------------------------*/
/* ---------------------------------------------------------------------------------*/
const BASE_URL = '/panel/brands/' ;
/* ---------------------------------------------------------------------------------*/

/* ---------------------------------------------------------------------------------*/
/* ---------------------------------------------------------------------------------*/
export const BrandService = {
    /* -----------------------------------------------------------------------------*/
    /* -----------------------------------------------------------------------------*/
    async getAll(params?: BrandFilterTypes): Promise<BrandApiPaginatedResponse<BrandTypes>> {
      const response = await api.get<BrandApiPaginatedResponse<BrandTypes>>(BASE_URL, { params });
      return response.data; 
    },
    /* -----------------------------------------------------------------------------*/
    
    /* -----------------------------------------------------------------------------*/
    /* -----------------------------------------------------------------------------*/
    async create(data: BrandFormData): Promise<BrandTypes> {
        const response = await api.post<BrandTypes>(BASE_URL, data, {
            headers: { 'Content-Type': 'multipart/form-data' }
        });
        return response.data;
    },
    /* -----------------------------------------------------------------------------*/

    /* -----------------------------------------------------------------------------*/
    /* -----------------------------------------------------------------------------*/
    async update(id: string | number, data: BrandFormData): Promise<BrandTypes> {
        const response = await api.put<BrandTypes>(`${BASE_URL}${id}/`, data, {
            headers: { 'Content-Type': 'multipart/form-data' }
        });
        return response.data;
    },
    /* -----------------------------------------------------------------------------*/

    /* -----------------------------------------------------------------------------*/
    /* -----------------------------------------------------------------------------*/
    async delete(id: string | number): Promise<void> {
      await api.delete(`${BASE_URL}${id}/`);
    },
    /* -----------------------------------------------------------------------------*/

    /* -----------------------------------------------------------------------------*/
    /* -----------------------------------------------------------------------------*/
    async bulkDelete(ids: (string | number)[]): Promise<void> {
      await api.delete(`${BASE_URL}bulk-delete/`, { data: { ids } });
    },
    /* -----------------------------------------------------------------------------*/


};
/* ---------------------------------------------------------------------------------*/


/* ---------------------------------------------------------------------------------*/
/* ---------------------------------------------------------------------------------*/
export const BrandForCreate = async (): Promise<BrandForCreateTypes[]> => {
    const response = await api.get('/panel/brands/list/for-create/');
    return response.data ;
};
/* ---------------------------------------------------------------------------------*/

/* ---------------------------------------------------------------------------------*/
/* ---------------------------------------------------------------------------------*/
export const PublicBrands = async (): Promise<BrandTypes[]> => {
    const response = await StoreApi.get('/public/brands/');
    return response.data ;
};
/* ---------------------------------------------------------------------------------*/

