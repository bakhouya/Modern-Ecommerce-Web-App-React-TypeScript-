import api from '../axiosInstance'; 
import type { UserFilterTypes, UserFormData, UsersResponseTypes, UserTypes } from '../../types/userTypes';
/* ---------------------------------------------------------------------------------*/


/* ---------------------------------------------------------------------------------*/
/* ---------------------------------------------------------------------------------*/
const BASE_URL = '/panel/users/' ;
/* ---------------------------------------------------------------------------------*/

/* ---------------------------------------------------------------------------------*/
/* ---------------------------------------------------------------------------------*/
export const UserService = {
    /* -----------------------------------------------------------------------------*/
    /* -----------------------------------------------------------------------------*/
    async getAll(params?: UserFilterTypes): Promise<UsersResponseTypes<UserTypes>> {
        const response = await api.get<UsersResponseTypes<UserTypes>>(BASE_URL, { params });
        return response.data; 
    },
    /* -----------------------------------------------------------------------------*/
    
    /* -----------------------------------------------------------------------------*/
    /* -----------------------------------------------------------------------------*/
    async create(data: UserFormData): Promise<UserTypes> {
        const response = await api.post<UserTypes>(BASE_URL, data, {
            headers: { 'Content-Type': 'multipart/form-data' }
        });
        return response.data;
    },
    /* -----------------------------------------------------------------------------*/

    /* -----------------------------------------------------------------------------*/
    /* -----------------------------------------------------------------------------*/
    async update(id: string | number, data: UserFormData): Promise<UserTypes> {
        const response = await api.put<UserTypes>(`${BASE_URL}${id}/`, data, {
            headers: { 'Content-Type': 'multipart/form-data' }
        });
        return response.data;
    },
    /* -----------------------------------------------------------------------------*/

    /* -----------------------------------------------------------------------------*/
    /* -----------------------------------------------------------------------------*/
    async delete(id: string | number): Promise<void> {
        await api.delete(`${BASE_URL}${id}/`);
    },
    /* -----------------------------------------------------------------------------*/

    /* -----------------------------------------------------------------------------*/
    /* -----------------------------------------------------------------------------*/
    async bulkDelete(ids: (string | number)[]): Promise<void> {
        await api.delete(`${BASE_URL}bulk-delete/`, { data: { ids } });
    },
    /* -----------------------------------------------------------------------------*/


};
