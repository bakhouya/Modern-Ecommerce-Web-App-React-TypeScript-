




/* ---------------------------------------------------------------------------------*/
/* ---------------------------------------------------------------------------------*/
import api from '../axiosInstance';
import type { SupplierApiPaginatedResponse, SupplierFilterTypes, SupplierFormData, SupplierTypes } from '../../types/supplierTypes';
/* ---------------------------------------------------------------------------------*/


/* ---------------------------------------------------------------------------------*/
/* ---------------------------------------------------------------------------------*/
const BASE_URL = '/panel/suppliers/';
/* ---------------------------------------------------------------------------------*/

/* ---------------------------------------------------------------------------------*/
/* ---------------------------------------------------------------------------------*/
export const SupplierService = {
    /* -----------------------------------------------------------------------------*/
    /* -----------------------------------------------------------------------------*/
    async getAll(params?: SupplierFilterTypes): Promise<SupplierApiPaginatedResponse<SupplierTypes>> {
      const response = await api.get<SupplierApiPaginatedResponse<SupplierTypes>>(BASE_URL, { params });
      return response.data; 
    },
    /* -----------------------------------------------------------------------------*/
    
    /* -----------------------------------------------------------------------------*/
    /* -----------------------------------------------------------------------------*/
    async create(data: SupplierFormData): Promise<SupplierTypes> {
        const response = await api.post<SupplierTypes>(BASE_URL, data);
        return response.data;
    },
    /* -----------------------------------------------------------------------------*/

    /* -----------------------------------------------------------------------------*/
    /* -----------------------------------------------------------------------------*/
    async update(id: string | number, data: SupplierFormData): Promise<SupplierTypes> {
        const response = await api.put<SupplierTypes>(`${BASE_URL}${id}/`, data);
        return response.data;
    },
    /* -----------------------------------------------------------------------------*/

    /* -----------------------------------------------------------------------------*/
    /* -----------------------------------------------------------------------------*/
    async delete(id: string | number): Promise<void> {
      await api.delete(`${BASE_URL}${id}/`);
    },
    /* -----------------------------------------------------------------------------*/

    /* -----------------------------------------------------------------------------*/
    /* -----------------------------------------------------------------------------*/
    async bulkDelete(ids: (string | number)[]): Promise<void> {
      await api.delete(`${BASE_URL}bulk-delete/`, { data: { ids } });
    },
    /* -----------------------------------------------------------------------------*/


};
/* ---------------------------------------------------------------------------------*/




