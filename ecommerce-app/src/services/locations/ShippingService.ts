
/* ---------------------------------------------------------------------------------*/
/* ---------------------------------------------------------------------------------*/
import api from '../axiosInstance';
import type { ShippingApiPaginatedResponse, ShippingFilterTypes, ShippingFormData, ShippingTypes } from '../../types/shippingsTypes';
/* ---------------------------------------------------------------------------------*/


/* ---------------------------------------------------------------------------------*/
/* ---------------------------------------------------------------------------------*/
const BASE_URL = '/panel/shippings/';
/* ---------------------------------------------------------------------------------*/

/* ---------------------------------------------------------------------------------*/
/* ---------------------------------------------------------------------------------*/
export const ShippingService = {
    /* -----------------------------------------------------------------------------*/
    /* -----------------------------------------------------------------------------*/
    async getAll(params?: ShippingFilterTypes): Promise<ShippingApiPaginatedResponse<ShippingTypes>> {
      const response = await api.get<ShippingApiPaginatedResponse<ShippingTypes>>(BASE_URL, { params });
      return response.data; 
    },
    /* -----------------------------------------------------------------------------*/
    
    /* -----------------------------------------------------------------------------*/
    /* -----------------------------------------------------------------------------*/
    async create(data: ShippingFormData): Promise<ShippingTypes> {
        const response = await api.post<ShippingTypes>(BASE_URL, data, {
            headers: { 'Content-Type': 'multipart/form-data' }
        });
        return response.data;
    },
    /* -----------------------------------------------------------------------------*/

    /* -----------------------------------------------------------------------------*/
    /* -----------------------------------------------------------------------------*/
    async update(id: string | number, data: ShippingFormData): Promise<ShippingTypes> {
        const response = await api.put<ShippingTypes>(`${BASE_URL}${id}/`, data, {
            headers: { 'Content-Type': 'multipart/form-data' }
        });
        
        return response.data;
    },
    /* -----------------------------------------------------------------------------*/

    /* -----------------------------------------------------------------------------*/
    /* -----------------------------------------------------------------------------*/
    async delete(id: string | number): Promise<void> {
      await api.delete(`${BASE_URL}${id}/`);
    },
    /* -----------------------------------------------------------------------------*/

    /* -----------------------------------------------------------------------------*/
    /* -----------------------------------------------------------------------------*/
    async bulkDelete(ids: (string | number)[]): Promise<void> {
      await api.delete(`${BASE_URL}bulk-delete/`, { data: { ids } });
    },
    /* -----------------------------------------------------------------------------*/


};
/* ---------------------------------------------------------------------------------*/





