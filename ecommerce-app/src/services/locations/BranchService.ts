import api from '../axiosInstance';
import type { BranchApiPaginatedResponse, BranchFilterTypes, BranchFormData, BranchTypes } from '../../types/branchTypes';
/* ---------------------------------------------------------------------------------*/


/* ---------------------------------------------------------------------------------*/
/* ---------------------------------------------------------------------------------*/
const BASE_URL = '/panel/branches/';   
/* ---------------------------------------------------------------------------------*/

/* ---------------------------------------------------------------------------------*/
/* ---------------------------------------------------------------------------------*/
export const BranchService = {
    /* -----------------------------------------------------------------------------*/
    /* -----------------------------------------------------------------------------*/
    async getAll(params?: BranchFilterTypes): Promise<BranchApiPaginatedResponse<BranchTypes>> {
      const response = await api.get<BranchApiPaginatedResponse<BranchTypes>>(BASE_URL, { params });
      return response.data; 
    },
    /* -----------------------------------------------------------------------------*/
    
    /* -----------------------------------------------------------------------------*/
    /* -----------------------------------------------------------------------------*/
    async create(data: BranchFormData): Promise<BranchTypes> {
        const response = await api.post<BranchTypes>(BASE_URL, data);
        return response.data;
    },
    /* -----------------------------------------------------------------------------*/

    /* -----------------------------------------------------------------------------*/
    /* -----------------------------------------------------------------------------*/
    async update(id: string | number, data: BranchFormData): Promise<BranchTypes> {
        const response = await api.put<BranchTypes>(`${BASE_URL}${id}/`, data);
        return response.data;
    },
    /* -----------------------------------------------------------------------------*/

    /* -----------------------------------------------------------------------------*/
    /* -----------------------------------------------------------------------------*/
    async delete(id: string | number): Promise<void> {
      await api.delete(`${BASE_URL}${id}/`);
    },
    /* -----------------------------------------------------------------------------*/

    /* -----------------------------------------------------------------------------*/
    /* -----------------------------------------------------------------------------*/
    async bulkDelete(ids: (string | number)[]): Promise<void> {
      await api.delete(`${BASE_URL}bulk-delete/`, { data: { ids } });
    },
    /* -----------------------------------------------------------------------------*/


};
/* ---------------------------------------------------------------------------------*/


/* ---------------------------------------------------------------------------------*/
/* ---------------------------------------------------------------------------------*/
export const ActiveBranchesService = async (): Promise<BranchTypes[]> => {
    const response = await api.get('/panel/active/branches/');
    return response.data ;
};
